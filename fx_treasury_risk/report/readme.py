"""Keep the README's results section in step with the decision report.

The README opens with the answer and the backtest numbers. Those change with every data
refresh, so they are not written by hand: the block between the two markers below is
rendered from the same data and the same functions as ``reports/decision_report.md``
(the headline paragraph, the policy table, the risk-model sentence), so the two can
never disagree. Everything outside the markers is hand-written and contains no numbers
that a refresh could make stale.

``fxrisk readme`` rewrites the block; ``fxrisk readme --check`` only reports whether it
is out of date. ``fxrisk all`` and the weekly refresh run it after the report stage.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from fx_treasury_risk import config
from fx_treasury_risk.report import decision
from fx_treasury_risk.report.tables import df_to_markdown

START = "<!-- results:start - generated by `fxrisk readme` from the decision report; edit there -->"
END = "<!-- results:end -->"
README = config.REPO_ROOT / "README.md"


def _forecast_text(d: decision.ReportData) -> str:
    f = d.forecast_by_horizon.set_index("horizon")
    h = d.hcfg.horizon_days
    first = int(f.index.min())
    skill_first = decision._num(f.loc[first, "skill_vs_naive"])
    skill_h = decision._num(f.loc[h, "skill_vs_naive"])
    err_lo, err_hi = float(f["mape_median_pct"].min()), float(f["mape_median_pct"].max())
    cov_lo, cov_hi = float(f["coverage_95"].min()), float(f["coverage_95"].max())
    days = "day" if first == 1 else "days"
    return (
        f"**Exposure forecasts (`reports/forecast_eval.md`):** skill against the seasonal "
        f"naive is {skill_first:.2f} at {first} {days} and {skill_h:.2f} at the {h}-day "
        f"policy horizon, with a median error of {err_lo:.0f}-{err_hi:.0f}% of exposure; "
        f"the 95% intervals cover {100 * cov_lo:.0f}-{100 * cov_hi:.0f}% of outcomes."
    )


def render_results(d: decision.ReportData) -> str:
    """The README's generated block, markers included."""
    opt = decision._policy_row(d.policy_summary, "optimizer")
    end = pd.Timestamp(d.as_of).year
    parts = [
        START,
        "",
        f"*Headline answer as of {d.as_of.date()}, copied from the "
        "[decision report](reports/decision_report.md) by every run:*",
        "",
        decision.headline_answer(d),
        "",
        f"**Out of sample, {d.hcfg.oos_start.year} to {end}, monthly rebalance, "
        f"{int(opt['n_months'])} months (`reports/policy_backtest.md`), USD m:**",
        "",
        df_to_markdown(decision._summary_table(d), decimals=decision.SUMMARY_DECIMALS),
        "",
        "**What the risk backtests say (`reports/var_backtest.md`):** the one-day coverage "
        f"backtest runs daily from {d.hcfg.oos_start.year}. " + decision._model_choice_text(d),
        "",
        _forecast_text(d),
        "",
        END,
    ]
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str:
    """``text`` with everything from START to END (inclusive) replaced by ``block``."""
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise ValueError("README has no results markers; add START and END lines first")
    return text[:i] + block + text[j + len(END) :]


def update_readme(paths: config.Paths, readme: Path = README, check: bool = False) -> bool:
    """Rewrite the README block from the database; returns True if it changed (or would)."""
    d = decision.load_report_data(paths)
    old = readme.read_text(encoding="utf-8")
    new = replace_block(old, render_results(d))
    if new != old and not check:
        readme.write_text(new, encoding="utf-8", newline="\n")
    return new != old
