"""Forecast models and evaluation on synthetic series with known structure."""

import numpy as np
import pandas as pd
import pytest

from fx_treasury_risk.forecast import calendar as fc
from fx_treasury_risk.forecast import evaluate as ev
from fx_treasury_risk.forecast import models


def _series(n: int = 1500, seed: int = 0) -> tuple[pd.Series, pd.DatetimeIndex]:
    """Log-level series with weekday, month-end and trend structure plus AR(1) noise."""
    rng = np.random.default_rng(seed)
    cal = pd.bdate_range("2016-01-04", periods=n)
    _from_start, to_end = fc.position_in_month(cal)
    level = 0.1 * (cal.year - 2016 + cal.month / 12)  # ~10%/yr trend
    weekday = np.where(cal.day_of_week == 4, 0.15, 0.0)
    eom = np.where(to_end == 0, -0.3, 0.0)
    e = np.zeros(n)
    for t in range(1, n):
        e[t] = 0.6 * e[t - 1] + rng.normal(0, 0.05)
    y = np.exp(17 + level + weekday + eom + e)
    return pd.Series(y, index=cal, name="EUR"), cal


def test_position_in_month() -> None:
    cal = pd.bdate_range("2024-01-29", "2024-02-05")  # Mon 29 Jan .. Mon 5 Feb
    from_start, to_end = fc.position_in_month(cal)
    assert list(to_end[:3]) == [2, 1, 0]  # 29, 30, 31 Jan: 31 Jan is the last trading day
    assert list(from_start[3:]) == [0, 1, 2]  # 1, 2, 5 Feb


def test_feature_matrix_columns_and_future_dates() -> None:
    cal = pd.bdate_range("2024-01-01", periods=40)
    x = fc.feature_matrix(cal, cal[0])
    assert x.shape[1] == 1 + 1 + 4 + 5 + 3 + 11
    assert (x["const"] == 1).all()
    # month ends are located on the full calendar, not on the requested dates
    mid = cal[cal.month == 1][:5]  # first five January trading days
    xm = fc.feature_matrix(mid, cal[0], cal)
    assert xm["to_eom_0"].sum() == 0 and xm["from_bom_0"].iloc[0] == 1
    fut = fc.future_dates(cal[20], 30, cal)  # 19 known days then weekdays
    assert len(fut) == 30 and fut[0] == cal[21] and fut.is_monotonic_increasing
    assert (fut.day_of_week < 5).all()


def test_pinball_loss_definition() -> None:
    y = np.array([1.0, 1.0])
    q = np.array([0.5, 1.5])
    np.testing.assert_allclose(ev.pinball_loss(y, q, 0.9), [0.45, 0.05])
    np.testing.assert_allclose(ev.pinball_loss(y, q, 0.1), [0.05, 0.45])


def test_calendar_ar1_recovers_structure_and_is_calibrated() -> None:
    y, cal = _series()
    fit = models.fit_calendar_ar1(y, window=750, calendar=cal)
    assert fit.phi == pytest.approx(0.6, abs=0.08)
    assert fit.sigma == pytest.approx(0.05, abs=0.01)
    coef = dict(zip(fit.columns, fit.beta, strict=True))
    assert coef["to_eom_0"] == pytest.approx(-0.3, abs=0.04)
    assert coef["trend_years"] == pytest.approx(0.1, abs=0.03)
    # rolling-origin coverage close to nominal on data generated by the model's own family
    origins = ev.monthly_origins(cal, pd.Timestamp("2019-01-01"), 63)
    f = ev.rolling_origin_forecasts(y, cal, origins, ("calendar_ar1", "seasonal_naive"), 63, 750)
    e = ev.evaluate(f)
    ar1 = e[(e.model == "calendar_ar1") & (e.horizon == 21)].iloc[0]
    assert 0.84 < ar1.coverage_95 <= 1.0 and 0.58 < ar1.coverage_80 < 0.95
    assert ar1.skill_vs_naive > 0.3  # the structural model beats the naive by a wide margin
    naive = e[(e.model == "seasonal_naive") & (e.horizon == 21)].iloc[0]
    assert naive.skill_vs_naive == pytest.approx(0.0)


def test_seasonal_naive_point_and_widening_intervals() -> None:
    y, cal = _series(n=400)
    f = models.seasonal_naive(y, cal, horizon=63, window=300)
    q = f.quantiles
    med = q[:, models.QUANTILES.index(0.5)]
    # horizon 1 repeats the value four weeks before the target (same weekday), times the
    # median error ratio, which is close to 1
    target = f.dates[0]
    src = y.index[y.index <= target - pd.Timedelta(days=28)][-1]
    assert src.day_of_week == target.day_of_week
    assert med[0] == pytest.approx(y.loc[src], rel=0.1)
    width = q[:, -1] / q[:, 0]
    assert width[41] >= width[0] * 0.95  # 42-day ahead uses 2 seasons back: not narrower
    assert f.to_frame().shape == (63, 2 + 2 + len(models.QUANTILES))


def test_monthly_origins_are_day_before_first_trading_day() -> None:
    cal = pd.bdate_range("2020-01-01", "2020-06-30")
    o = ev.monthly_origins(cal, pd.Timestamp("2020-02-01"), 10)
    assert o[0] == pd.Timestamp("2020-01-31")
    assert o[1] == pd.Timestamp("2020-02-28")
    assert all(cal[cal > d][0].month != d.month for d in o)
